    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        int id = Integer.valueOf(txtId.getText());
        String nome = txtNome.getText();
        String codenome = txtCodenome.getText();
        String cnpj = txtCnpj.getText();
        if (fornecedorController.Update(id, nome, codenome, cnpj)) {
            JOptionPane.showMessageDialog(this, "Fornecedor alterado com sucesso");
        } else {
            JOptionPane.showMessageDialog(this, "ID não encontrado");
        }
        popularTabela(fornecedorController.getAll());      
    }//GEN-LAST:event_btnAlterarActionPerformed

    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        String nome = txtNome.getText();
        String codenome = txtCodenome.getText();
        String cnpj = txtCnpj.getText();
//        char[] senhaArray = txtSenha.getPassword();
//        String senha = new String(senhaArray);
//        senha = BCrypt.hashpw(senha, BCrypt.gensalt());
        fornecedorController.add(nome, codenome, cnpj);

        JOptionPane.showMessageDialog(this, "Usuario salvo com sucesso");
        popularTabela(fornecedorController.getAll());
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
            int resposta = JOptionPane.showConfirmDialog(this, "Tem certeza?", "Confirmar exclusão", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);

        if (resposta == JOptionPane.YES_OPTION) {
            int id = Integer.valueOf(txtId.getText());
            if (fornecedorController.Delete(id)) {
                JOptionPane.showMessageDialog(this, "Fornecedor excluido com sucesso");
            } else {
                JOptionPane.showMessageDialog(this, "ID não encontrado");
            }
            popularTabela(fornecedorController.getAll());
        } else {
            JOptionPane.showMessageDialog(this, "Te liga bicho");
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

