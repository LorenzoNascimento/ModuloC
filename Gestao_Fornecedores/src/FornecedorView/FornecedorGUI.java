    public void popularTabela(ArrayList<Fornecedor> fornecedor) {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("ID");
        model.addColumn("Nome");
        model.addColumn("Codenome");
        model.addColumn("Cnpj");

        for (Fornecedor f : fornecedor) {
            model.addRow(new Object[]{f.getId(), f.getNome(), f.getCodenome(), f.getCnpj()});
        }
        tblFornecedor.setModel(model);
    }
